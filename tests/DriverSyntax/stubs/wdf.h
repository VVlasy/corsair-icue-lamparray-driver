#define WDF_OBJECT_ATTRIBUTES_INIT(attributes)                    \
    do {                                                          \
        RtlZeroMemory((attributes), sizeof(WDF_OBJECT_ATTRIBUTES)); \
        (attributes)->Size = sizeof(WDF_OBJECT_ATTRIBUTES);       \
    } while (0)

/*
 * The real macro also wires up the context type info generated by
 * WDF_DECLARE_CONTEXT_TYPE_WITH_NAME.  Here it only needs to compile and to
 * reference the type, so that a mismatched type name is still an error.
 */
#define WDF_OBJECT_ATTRIBUTES_INIT_CONTEXT_TYPE(attributes, contextType)  \
    do {                                                                  \
        WDF_OBJECT_ATTRIBUTES_INIT(attributes);                           \
        (attributes)->ContextSizeOverride = sizeof(contextType);          \
    } while (0)

#define WDF_DRIVER_CONFIG_INIT(config, deviceAdd)             \
    do {                                                      \
        RtlZeroMemory((config), sizeof(WDF_DRIVER_CONFIG));   \
        (config)->Size = sizeof(WDF_DRIVER_CONFIG);           \
        (config)->EvtDriverDeviceAdd = (deviceAdd);           \
    } while (0)

#define WDF_IO_QUEUE_CONFIG_INIT(config, dispatch)              \
    do {                                                        \
        RtlZeroMemory((config), sizeof(WDF_IO_QUEUE_CONFIG));   \
        (config)->Size = sizeof(WDF_IO_QUEUE_CONFIG);           \
        (config)->DispatchType = (dispatch);                    \
        (config)->PowerManaged = FALSE;                         \
    } while (0)

#define WDF_IO_QUEUE_CONFIG_INIT_DEFAULT_QUEUE(config, dispatch) \
    do {                                                         \
        WDF_IO_QUEUE_CONFIG_INIT((config), (dispatch));          \
        (config)->DefaultQueue = TRUE;                           \
    } while (0)

/*
 * Generates the typed context accessor.  The real macro emits an inline
 * definition as well as a declaration, so this must too -- declaring it alone
 * would leave every caller with an unresolved symbol at link time.
 */
#define WDF_DECLARE_CONTEXT_TYPE_WITH_NAME(contextType, accessorName)  \
    inline contextType *accessorName(WDFOBJECT object)                 \
    {                                                                  \
        (void)object;                                                  \
        static contextType claStubContextStorage;                      \
        return &claStubContextStorage;                                 \
    }

